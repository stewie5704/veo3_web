vi_file = Path("frontend/src/locales/vi.json")
en_file = Path("frontend/src/locales/en.json")

def update_json(path, updates):
    if not path.exists(): return
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    data.update(updates)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

update_json(vi_file, vi_additions)
update_json(en_file, en_additions)
print("Done!")
